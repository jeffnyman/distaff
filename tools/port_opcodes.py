"""Generates OpcodeTable.g.cs from ScummVM's engines/scumm/script_v5.cpp, script_v4.cpp and script_v3.cpp.

Loom's EGA release runs ScummEngine_v3old, whose opcode table is ScummEngine_v5::setupOpcodes
with the changes of ScummEngine_v4::setupOpcodes and then of ScummEngine_v3::setupOpcodes applied
in turn. Lines commented out are skipped, as is the Sega CD block of the v5 table; the v3 table's
PC Engine condition is taken as false, as it is for every release but the PC Engine's. An opcode
v4 disables and v3 does not restore is left empty. Run from the repository root:

    python tools/port_opcodes.py ../_loom/scummvm/engines/scumm > src/Distaff.Scumm/Scripts/OpcodeTable.g.cs
"""

import os
import re
import sys

OPCODE = re.compile(r"OPCODE\((0x[0-9a-fA-F]{2}), (\w+)\);")
DISABLE = re.compile(r"_opcodes\[(0x[0-9a-fA-F]{2})\]\.setProc\(nullptr, nullptr\);")


def body(path, engine):
    with open(path, encoding="utf-8") as handle:
        source = handle.read()
    found = re.search(r"void " + engine + r"::setupOpcodes\(\) \{(.*?)\n\}", source, re.S)
    if not found:
        sys.exit(f"no {engine}::setupOpcodes in {path}")
    lines = [line for line in found.group(1).splitlines() if not line.strip().startswith("//")]
    text = "\n".join(lines)
    # the v5 table's Sega CD fix is an if block of its own; nothing else in these tables is conditional
    return re.sub(r"if \(_game\.id == GID_MONKEY && _game\.platform == Common::kPlatformSegaCD.*?\n\t\}", "", text, flags=re.S)


def apply(table, text):
    for line in text.splitlines():
        if (m := OPCODE.search(line)):
            table[int(m.group(1), 16)] = m.group(2)
        elif (m := DISABLE.search(line)):
            table[int(m.group(1), 16)] = None


def main(folder):
    table = {}
    apply(table, body(os.path.join(folder, "script_v5.cpp"), "ScummEngine_v5"))
    apply(table, body(os.path.join(folder, "script_v4.cpp"), "ScummEngine_v4"))
    apply(table, body(os.path.join(folder, "script_v3.cpp"), "ScummEngine_v3"))
    if sorted(table) != list(range(256)):
        sys.exit(f"the tables define {len(table)} opcodes, not 256")

    print("// <auto-generated>")
    print("// Generated by tools/port_opcodes.py from ScummVM's engines/scumm/script_v5.cpp, script_v4.cpp and script_v3.cpp. Do not edit.")
    print("// </auto-generated>")
    print()
    print("#nullable enable")
    print()
    print("namespace Distaff.Scumm.Scripts;")
    print()
    print("internal static class OpcodeTable")
    print("{")
    print("    /// <summary>")
    print("    /// The ScummVM handler of each opcode of version 3, or null for an opcode no handler is set for.")
    print("    /// Mirrors <c>ScummEngine_v3::setupOpcodes</c> over <c>ScummEngine_v4</c>'s and <c>ScummEngine_v5</c>'s.")
    print("    /// </summary>")
    print("    public static readonly string?[] Handlers =")
    print("    [")
    for op in range(256):
        name = table[op]
        print(f'        {"null" if name is None else chr(34) + name + chr(34)}, // 0x{op:02X}')
    print("    ];")
    print("}")


if __name__ == "__main__":
    main(sys.argv[1])

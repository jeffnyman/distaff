"""Generates ScummMd5Table.g.cs from ScummVM's engines/scumm/scumm-md5.h.

Only the Loom rows are kept. Run from the repository root:

    python tools/port_md5_table.py ../_loom/scummvm/engines/scumm/scumm-md5.h > src/Distaff.Scumm/Detection/ScummMd5Table.g.cs
"""

import re
import sys

ROW = re.compile(
    r'\{\s*"([0-9a-f]{32})",\s*"(\w+)",\s*"([^"]*)",\s*"([^"]*)",\s*(-?\d+)\s*,\s*Common::(\w+),\s*Common::(\w+)\s*\}'
)

LANGUAGES = {
    "EN_ANY": "en", "EN_USA": "en", "EN_GRB": "en", "DE_DEU": "de", "FR_FRA": "fr",
    "ES_ESP": "es", "IT_ITA": "it", "RU_RUS": "ru", "HE_ISR": "he", "CA_ESP": "ca",
    "SV_SWE": "sv", "JA_JPN": "ja", "KO_KOR": "ko", "PT_BRA": "pt", "PL_POL": "pl",
    "HU_HUN": "hu", "ZH_TWN": "zh", "UNK_LANG": None,
}

PLATFORMS = {
    "kPlatformDOS": "dos", "kPlatformAmiga": "amiga", "kPlatformAtariST": "atari",
    "kPlatformFMTowns": "fmtowns", "kPlatformPCEngine": "pce", "kPlatformMacintosh": "mac",
    "kPlatformWindows": "windows", "kPlatformUnknown": None,
}


def literal(value):
    return "null" if value is None else f'"{value}"'


def main(path):
    with open(path, encoding="utf-8") as header:
        rows = [m.groups() for m in ROW.finditer(header.read()) if m.group(2) == "loom"]

    print("// <auto-generated>")
    print("// Generated by tools/port_md5_table.py from ScummVM's engines/scumm/scumm-md5.h. Do not edit.")
    print("// </auto-generated>")
    print()
    print("namespace Distaff.Scumm.Detection;")
    print()
    print("internal static partial class ScummMd5Table")
    print("{")
    print("    public static readonly Md5Entry[] Entries =")
    print("    [")
    for md5, game, variant, extra, size, language, platform in rows:
        print(
            f'        new("{md5}", "{game}", "{variant}", "{extra}", {size}, '
            f"{literal(LANGUAGES[language])}, {literal(PLATFORMS[platform])}),"
        )
    print("    ];")
    print("}")


if __name__ == "__main__":
    main(sys.argv[1])
